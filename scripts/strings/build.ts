// Builds the web's and the phone's strings from apps/strings/en.yaml (decisions.md N19).
// `bun scripts/strings/build.ts` writes both files; `--check` fails when either is out of date.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dir, '..', '..')
export const CATALOGUE = join(ROOT, 'apps/strings/en.yaml')
export const WEB_OUT = join(ROOT, 'apps/hq-web/src/strings/en.gen.ts')
export const ANDROID_OUT = join(ROOT, 'apps/android/app/src/main/res/values/strings_catalogue.xml')

const KEY = /^[a-z][a-z0-9_]*$/
const PLACEHOLDER = /\{([a-z][a-z0-9_]*)\}/g
const PLURAL_FORMS = new Set(['zero', 'one', 'two', 'few', 'many', 'other'])

export type Entry = string | Record<string, string>
export type Catalogue = Record<string, Entry>

/** Reads and checks the catalogue: snake_case keys, plurals with an `other` form, no fragments. */
export function load(text = readFileSync(CATALOGUE, 'utf8')): Catalogue {
  const raw = Bun.YAML.parse(text) as Record<string, unknown>
  const out: Catalogue = {}
  for (const [key, value] of Object.entries(raw ?? {})) {
    if (!KEY.test(key)) throw new Error(`${key}: keys are snake_case`)
    if (typeof value === 'string') {
      out[key] = value
      continue
    }
    if (!value || typeof value !== 'object') throw new Error(`${key}: a sentence or a plural map`)
    const forms = value as Record<string, unknown>
    for (const [form, s] of Object.entries(forms)) {
      if (!PLURAL_FORMS.has(form) || typeof s !== 'string') throw new Error(`${key}.${form}: not a plural form`)
    }
    if (typeof forms.other !== 'string') throw new Error(`${key}: a plural needs an other form`)
    out[key] = forms as Record<string, string>
  }
  return out
}

export function placeholders(s: string): string[] {
  return [...new Set([...s.matchAll(PLACEHOLDER)].map((m) => m[1]))]
}

/** Where the web app and HQ Hub read their words; the web file carries only the keys these name. */
const WEB_SOURCES = [join(ROOT, 'apps/hq-web/src'), join(ROOT, 'apps/desktop/ui/src')]
const SOURCE_FILE = /\.(ts|tsx)$/

function sourceText(dirs: string[]): string {
  const out: string[] = []
  const walk = (dir: string) => {
    if (!existsSync(dir)) return
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) walk(path)
      else if (SOURCE_FILE.test(name) && path !== WEB_OUT) out.push(readFileSync(path, 'utf8'))
    }
  }
  dirs.forEach(walk)
  return out.join('\n')
}

/** Whether the code names `key`: as a quoted key, or by a prefix it builds keys from (`note_export_${f}`). */
export function webUses(key: string, code: string): boolean {
  if (code.includes(`'${key}'`) || code.includes(`"${key}"`) || code.includes('`' + key + '`')) return true
  const parts = key.split('_')
  for (let i = 1; i < parts.length; i++) {
    const pre = parts.slice(0, i).join('_') + '_'
    if (code.includes('`' + pre + '${') || code.includes(`'${pre}' +`) || code.includes(`"${pre}" +`)) return true
  }
  return false
}

/** The web's share of the catalogue: the phone's own sentences stay out of the page and the worker. */
export function webKeys(cat: Catalogue, code: string = sourceText(WEB_SOURCES)): Catalogue {
  return Object.fromEntries(Object.entries(cat).filter(([k]) => webUses(k, code)))
}

export function webFile(cat: Catalogue): string {
  const lines = Object.entries(cat).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
  return `// Generated by scripts/strings/build.ts from apps/strings/en.yaml. Do not edit.\nexport const en = {\n${lines.join('\n')}\n} as const\n`
}

/** Android string resources: `{name}` becomes `%N$s` in order of first use, apostrophes escaped. */
function androidText(s: string): string {
  const order = placeholders(s)
  const escaped = s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/@/g, '\\@')
    .replace(/\?/g, '\\?')
  return escaped.replace(PLACEHOLDER, (_m, name: string) => `%${order.indexOf(name) + 1}$s`)
}

export function androidFile(cat: Catalogue): string {
  const body = Object.entries(cat).map(([k, v]) => {
    if (typeof v === 'string') return `    <string name="${k}">${androidText(v)}</string>`
    const items = Object.entries(v).map(([form, s]) => `        <item quantity="${form}">${androidText(s)}</item>`)
    return `    <plurals name="${k}">\n${items.join('\n')}\n    </plurals>`
  })
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/strings/build.ts from apps/strings/en.yaml. Do not edit. -->\n<resources>\n${body.join('\n')}\n</resources>\n`
}

function main() {
  const cat = load()
  const outputs: [string, string][] = [
    [WEB_OUT, webFile(webKeys(cat))],
    [ANDROID_OUT, androidFile(cat)],
  ]
  if (process.argv.includes('--check')) {
    const stale = outputs.filter(([p, text]) => !existsSync(p) || readFileSync(p, 'utf8') !== text)
    if (stale.length) {
      console.error(`Out of date: ${stale.map(([p]) => p).join(', ')}. Run bun scripts/strings/build.ts`)
      process.exit(1)
    }
    return
  }
  for (const [p, text] of outputs) writeFileSync(p, text)
  console.log(`Wrote ${Object.keys(cat).length} strings to the web and the phone.`)
}

if (import.meta.main) main()
