#!/usr/bin/env bash
# Tests file-size.py against throwaway trees. No network.
# Run: bash scripts/ci/file-size-test.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
t=$(mktemp -d)
trap 'rm -rf "$t"' EXIT
fails=0

new_root() { root=$(mktemp -d -p "$t"); mkdir -p "$root/crates/demo/src" "$root/scripts/ci"; }
run() { python3 -I "$here/file-size.py" --root "$root" "$@"; }
ok() { if "$@" > "$t/out" 2>&1; then :; else echo "FAIL (should pass): $*" >&2; cat "$t/out" >&2; fails=$((fails + 1)); fi; }
no() { if "$@" > "$t/out" 2>&1; then echo "FAIL (should refuse): $*" >&2; fails=$((fails + 1)); fi; }
says() { grep -qF -- "$1" "$t/out" || { echo "FAIL: output lacks '$1'" >&2; cat "$t/out" >&2; fails=$((fails + 1)); }; }
# lines N: N lines of plain code
lines() { awk -v n="$1" 'BEGIN{for(i=1;i<=n;i++) printf "fn f%d() {}\n", i}'; }
allow() { printf '[allow]\n%s\n' "$1" > "$root/scripts/ci/file-size-allow.toml"; }

# 1. A synthetic 1,501 line file fails; 1,500 passes.
new_root; lines 1501 > "$root/crates/demo/src/big.rs"; no run; says "1501 production lines, over 1500"
new_root; lines 1500 > "$root/crates/demo/src/big.rs"; ok run

# 2. Inline tests do not count: 1,501 lines of which 700 are a #[cfg(test)] module.
new_root
{ lines 801; printf '#[cfg(test)]\nmod tests {\n'; lines 698; printf '}\n'; } > "$root/crates/demo/src/a.rs"
ok run
# ...but the same file without the attribute does count.
new_root
{ lines 801; printf 'mod tests {\n'; lines 698; printf '}\n'; } > "$root/crates/demo/src/a.rs"
no run

# 3. Braces in strings, raw strings, comments and chars do not confuse the cut.
new_root
{ lines 1000
  printf '#[cfg(test)]\nmod tests {\n'
  printf '    const A: &str = "}}}}";\n    const B: &str = r#"}{ " }"#;\n    // } } }\n    /* { { { */\n    const C: char = '"'"'}'"'"';\n    fn lifetime<'"'"'a>(x: &'"'"'a str) {}\n'
  lines 800
  printf '}\n'
  lines 400; } > "$root/crates/demo/src/tricky.rs"
ok run        # 1000 + 400 production lines, the 800+ inside the test module are cut
ok run --top 1; says "1400  crates/demo/src/tricky.rs"   # exactly 1000 + 400: nothing else was counted

# 4. A test-only item that is not a module, and a bodiless `#[cfg(test)] mod tests;`.
new_root
{ lines 1499; printf '#[cfg(test)]\nfn helper() {\n'; lines 300; printf '}\n#[cfg(test)]\nmod tests;\n'; } > "$root/crates/demo/src/b.rs"
ok run

# 5. Files that are not measured: tests.rs, *_tests.rs, tests/ folders, build.rs, generated files.
new_root
for f in tests.rs thing_tests.rs build.rs table.gen.rs; do lines 2000 > "$root/crates/demo/src/$f"; done
mkdir -p "$root/crates/demo/src/tests"; lines 2000 > "$root/crates/demo/src/tests/x.rs"
{ printf '// @generated by a tool\n'; lines 2000; } > "$root/crates/demo/src/marked.rs"
mkdir -p "$root/crates/demo/tests"; lines 2000 > "$root/crates/demo/tests/it.rs"   # not under src/
ok run

# 6. Warning between 1,000 and 1,500, still passing.
new_root; lines 1200 > "$root/crates/demo/src/mid.rs"; ok run; says "warn: crates/demo/src/mid.rs: 1200 production lines"

# 7. The allowlist: at its size passes; above its size, below its cap, no longer over and a missing path all fail.
new_root; lines 1600 > "$root/crates/demo/src/big.rs"
allow '"crates/demo/src/big.rs" = 1600'; ok run
allow '"crates/demo/src/big.rs" = 1700'; no run; says "lower the cap to 1600"
allow '"crates/demo/src/big.rs" = 1500'; no run; says "grew to 1600 production lines, past its cap of 1500"
new_root; lines 1400 > "$root/crates/demo/src/small.rs"
allow '"crates/demo/src/small.rs" = 1600'; no run; says "no longer over 1500: delete it"
new_root; lines 10 > "$root/crates/demo/src/x.rs"
allow '"crates/demo/src/gone.rs" = 1600'; no run; says "not a measured file"

# 8. The real repository passes.
ok python3 -I "$here/file-size.py"

if [ "$fails" -gt 0 ]; then echo "$fails failed" >&2; exit 1; fi
echo "all passed"
